// Builds Space Works brand guidelines v2.
//   node brand/guidelines-v2/build.mjs          -> src/index.html, the PDF and png/NN.png
//   node brand/guidelines-v2/build.mjs --html   -> src/index.html only
// Pages live in src/pages/*.html (sorted by name). Placeholders resolved here:
//   {{box}}                      box-open markup (motion/box-open/box-open-markup.html)
//   {{svg:path}}                 inline an SVG from the repo root (width/height stripped)
//   {{cr:A/B}}                   WCAG contrast of A on B, 2 decimals. A, B = token path
//                                (light.ink, dark.panel, brand.citron, chart.dark.info, loader.light.under) or #hex
//   {{hex:path}}                 a token's hex value
//   {{qr:name}}                  inline src/qr/name.svg
//   {{toc}}                      contents list
// Header and footer of each <section class="pg" data-sec="..."> are injected with the page number.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, statSync, existsSync } from "node:fs";
import { spawn } from "node:child_process";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const src = join(here, "src");
const tokens = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8"));
const FOOTER = "Design System v2.0 · Brand guidelines v2";

// ---------- colour maths ----------
const hexOf = (ref) => {
  if (ref.startsWith("#")) return ref.toUpperCase();
  const v = ref.split(".").reduce((o, k) => o?.[k], tokens);
  if (typeof v !== "string" || !v.startsWith("#")) throw new Error(`no colour token ${ref}`);
  return v.toUpperCase();
};
const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
export const contrast = (a, b) => {
  const [x, y] = [lum(hexOf(a)), lum(hexOf(b))].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const triplet = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");

// ---------- generated theme CSS (colours only from tokens.json) ----------
function themeCss() {
  const block = (name, set, chart, loader) => {
    const lines = Object.entries(set).map(([k, v]) => `  --color-${k}: ${triplet(v)};`);
    Object.entries(chart).forEach(([k, v]) => lines.push(`  --chart-${k}: ${triplet(v)};`));
    Object.entries(loader).forEach(([k, v]) => lines.push(`  --loader-${k}: ${triplet(v)};`));
    return `.${name} {\n${lines.join("\n")}\n}`;
  };
  const brand = Object.entries(tokens.brand).map(([k, v]) => `  --b-${k}: ${triplet(v)};`).join("\n");
  const cards = ["light", "dark"].map((t) => `.card-${t} {\n${Object.entries(tokens.cards.aurora[t])
    .map(([k, v]) => `  --card-${k}: ${triplet(v)};`).join("\n")}\n}`).join("\n");
  const dk = ["line", "ink", "muted"].map((k) => `  --dk-${k}: ${triplet(tokens.dark[k])};`).join("\n");
  return `/* Generated by build.mjs from tokens/tokens.json. Do not edit. */\n:root {\n${brand}\n${dk}\n}\n` +
    block("th-light", tokens.light, tokens.chart.light, tokens.loader.light) + "\n" +
    block("th-dark", tokens.dark, tokens.chart.dark, tokens.loader.dark) + "\n" + cards + "\n";
}

// ---------- assemble ----------
function assemble() {
  const box = readFileSync(join(root, "motion/box-open/box-open-markup.html"), "utf8").trim();
  const files = readdirSync(join(src, "pages")).filter((f) => f.endsWith(".html")).sort();
  let body = files.map((f) => readFileSync(join(src, "pages", f), "utf8")).join("\n");
  let n = 0;
  const toc = [];
  body = body.replace(/<section class="pg([^"]*)"([^>]*)>/g, (m, cls, attrs) => {
    n += 1;
    const sec = /data-sec="([^"]*)"/.exec(attrs)?.[1] ?? "";
    const tocName = /data-toc="([^"]*)"/.exec(attrs)?.[1];
    if (tocName) toc.push([sec.split(" / ")[0], tocName, n]);
    const num = String(n).padStart(2, "0");
    return `<section class="pg${cls}"${attrs} id="p${num}">` +
      `<header class="hd"><span>space works / brand guidelines</span><span>${sec.toUpperCase()}</span></header>` +
      `<footer class="ft"><span>${FOOTER}</span><b>${num}</b></footer>`;
  });
  const tocHtml = toc.map(([no, name, p]) =>
    `<li><span class="toc-no">${no}</span><span class="toc-name">${name}</span><span class="toc-pg">${String(p).padStart(2, "0")}</span></li>`).join("");
  // {{strip:once|loop|hov:light|dark|mono:0|Label,200,...}} -> a row of frozen frames from the real box-open CSS
  body = body.replace(/\{\{strip:([a-z]+):([a-z]+):([^}]+)\}\}/g, (m, mode, ground, list) => {
    const frames = list.split(",").map((s) => s.split("|"));
    const g = ground === "mono" ? "g-light mono" : `g-${ground}`;
    return `<div class="strip" style="grid-template-columns:repeat(${frames.length},1fr)">` + frames.map(([t, k]) =>
      `<div class="fr"><div class="sw-box ${mode} ${g} frz boxf" style="--t:${t}">{{box}}</div>` +
      `<span class="t">${Number(t) >= 1000 ? (Number(t) / 1000).toLocaleString("en", { minimumFractionDigits: 1 }) + " s" : t + " ms"}</span>` +
      `<span class="k">${k ?? ""}</span></div>`).join("") + "</div>";
  });
  // {{ladder:light|dark}} neutral roles; {{fam:light|dark}} accent and status families
  const LADDER = [["bg", "Page"], ["surface", "Layer 1 · sidebar in dark"], ["panel", "Cards, dialogs"], ["hover", "Hover fill"],
    ["line", "Divider, decorative"], ["outline", "Control edges, at least 3:1"], ["muted", "Secondary text"], ["ink", "Text"],
    ["focus", "Focus ring"], ["scrim", "Dialog backdrop"]];
  body = body.replace(/\{\{ladder:(light|dark)\}\}/g, (m, th) => `<table class="tb ladder"><tbody>` + LADDER.map(([k, role]) => {
    const vs = ["ink", "muted", "outline", "line", "focus"].includes(k) ? `${contrast(`${th}.${k}`, `${th}.bg`).toFixed(2)} : 1` : "";
    return `<tr><td style="width:62px;padding:6px 14px 6px 0"><div class="chip" style="height:30px;background:rgb(var(--color-${k}));border:1px solid rgb(var(--color-line))"></div></td>` +
      `<td style="width:96px;font-weight:600">${k}</td><td class="code" style="width:92px">${hexOf(`${th}.${k}`)}</td><td>${role}</td><td class="num">${vs}</td></tr>`;
  }).join("") + `</tbody></table>`);
  const FAMS = [["accent", ["accent", "accent-hover", "accent-active", "accent-soft", "accent-ink"], "on-accent"],
    ["emphasis", ["emphasis", "emphasis-hover", "emphasis-active", "emphasis-soft"], "on-emphasis"],
    ["success", ["success", "success-hover", "success-active", "success-soft", "success-ink"], "on-success"],
    ["warn", ["warn", "warn-hover", "warn-active", "warn-soft", "warn-ink"], "on-warn"],
    ["info", ["info", "info-hover", "info-active", "info-soft", "info-ink"], "on-info"],
    ["danger", ["danger", "danger-hover", "danger-active", "danger-line"], "on-danger"]];
  body = body.replace(/\{\{fam:(light|dark)\}\}/g, (m, th) => `<div class="fams">` + FAMS.map(([name, keys, on]) =>
    `<div class="fam"><div class="fam-n">${name}</div>` + keys.map((k) => {
      const isInk = k.endsWith("-ink");
      const isFill = !k.includes("soft") && !isInk && !k.endsWith("line");
      const inner = isFill ? `<span style="color:rgb(var(--color-${on}))">Aa</span>` : isInk ? `<span style="color:rgb(var(--color-${k}))">Aa</span>` : "";
      const bgc = isInk ? "panel" : k;
      return `<div class="fc"><div class="chip fcs" style="background:rgb(var(--color-${bgc}));${isInk || k.includes("soft") ? "border:1px solid rgb(var(--color-line));" : ""}">${inner}</div>` +
        `<div class="xs" style="font-weight:600">${k.replace(name + "-", "") === name ? "fill" : k.replace(name + "-", "")}</div><div class="xs code mut">${hexOf(`${th}.${k}`)}</div></div>`;
    }).join("") + `</div>`).join("") + `</div>`);
  // {{chart}}: sample bars and lines drawn with the chart tokens (1 px edge on fills, 4 px casing under 2 px lines)
  const bars = [120, 92, 150, 70, 104].map((h, i) =>
    `<rect x="${12 + i * 42}" y="${190 - h}" width="30" height="${h}" rx="3" style="fill:rgb(var(--chart-${i + 1}));stroke:rgb(var(--chart-edge))" stroke-width="1"/>`).join("");
  const lines = [["1", "", "150 120 128 92 100 70 64 44"], ["2", "8 4", "170 160 150 152 130 128 112 100"], ["4", "10 3 2 3", "186 182 176 178 168 160 162 150"]]
    .map(([k, dash, ys]) => {
      const pts = ys.split(" ").map((y, j) => `${262 + j * 36},${y}`).join(" ");
      const da = dash ? ` stroke-dasharray="${dash}"` : "";
      return `<polyline points="${pts}" style="stroke:rgb(var(--chart-edge))" stroke-width="4"${da}/>` +
        `<polyline points="${pts}" style="stroke:rgb(var(--chart-${k}))" stroke-width="2"${da}/>`;
    }).join("");
  const chart = `<svg viewBox="0 0 520 200" style="width:100%;display:block" fill="none" stroke-linejoin="round">` +
    `<path d="M0 190.5H220M250 190.5H520" style="stroke:rgb(var(--color-line))"/>${bars}${lines}</svg>` +
    `<div class="row xs mt8" style="justify-content:space-between"><span>Bars: 1 px edge on every fill</span><span>Lines: 2 px over a 4 px casing</span></div>`;
  body = body.replace(/\{\{chart\}\}/g, chart);
  body = body
    .replace(/\{\{toc\}\}/g, tocHtml)
    .replace(/\{\{box\}\}/g, box)
    .replace(/\{\{svg:([^}]+)\}\}/g, (m, p) => readFileSync(join(root, p), "utf8")
      .replace(/<\?xml[^>]*>/, "").replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, "<svg$1")
      .replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, "<svg$1"))
    .replace(/\{\{qr:([^}]+)\}\}/g, (m, p) => readFileSync(join(src, "qr", `${p}.svg`), "utf8").replace(/<\?xml[^>]*>/, ""))
    .replace(/\{\{cr:([^/}]+)\/([^}]+)\}\}/g, (m, a, b) => contrast(a, b).toFixed(2))
    .replace(/\{\{hex:([^}]+)\}\}/g, (m, p) => hexOf(p));
  const left = body.match(/\{\{[^}]*\}\}/);
  if (left) throw new Error(`unresolved placeholder ${left[0]}`);
  writeFileSync(join(src, "generated.css"), themeCss());
  const html = readFileSync(join(src, "shell.html"), "utf8").replace("<!--PAGES-->", body);
  writeFileSync(join(src, "index.html"), html);
  return n;
}

// ---------- render with headless Edge over the DevTools protocol ----------
const EDGE = "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function render(pages) {
  const profile = join(tmpdir(), `sw-guidelines-edge-${process.pid}`);
  const port = 9300 + (process.pid % 500);
  const edge = spawn(EDGE, ["--headless=new", "--disable-gpu", "--hide-scrollbars", "--no-first-run",
    `--remote-debugging-port=${port}`, `--user-data-dir=${profile}`, "about:blank"], { stdio: "ignore" });
  try {
    let target;
    for (let i = 0; i < 50 && !target; i += 1) {
      await sleep(200);
      try { target = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find((t) => t.type === "page"); } catch { /* not up yet */ }
    }
    if (!target) throw new Error("Edge did not start");
    const ws = new WebSocket(target.webSocketDebuggerUrl);
    await new Promise((r, j) => { ws.onopen = r; ws.onerror = j; });
    let id = 0;
    const waiting = new Map();
    ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && waiting.has(m.id)) { waiting.get(m.id)(m); waiting.delete(m.id); } };
    const cmd = (method, params = {}) => new Promise((r, j) => {
      id += 1; waiting.set(id, (m) => (m.error ? j(new Error(`${method}: ${m.error.message}`)) : r(m.result)));
      ws.send(JSON.stringify({ id, method, params }));
    });
    const evaluate = async (expression) => (await cmd("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true })).result.value;

    await cmd("Page.enable");
    await cmd("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
    await cmd("Page.navigate", { url: pathToFileURL(join(src, "index.html")).href });
    for (let i = 0; i < 100; i += 1) { await sleep(150); if ((await evaluate("document.readyState")) === "complete") break; }
    await evaluate("document.fonts.ready.then(() => true)");
    await evaluate("Promise.all([...document.images].map(i => i.complete ? 1 : new Promise(r => { i.onload = i.onerror = r; })))");
    await sleep(800);
    const fonts = await evaluate(`[["800 20px Gilroy"],["300 20px Gilroy"],["400 20px Outfit"],["600 20px Unbounded"]].map(([f]) => f + ":" + document.fonts.check(f)).join(" ")`);
    const loaded = await evaluate(`[...document.fonts].filter(f => f.status === "loaded").map(f => f.family + " " + f.weight).join(", ")`);
    console.log("font check:", fonts, "| loaded:", loaded);
    const overflow = await evaluate(`[...document.querySelectorAll('.pg')].map((p, i) => {
      const r = p.getBoundingClientRect(); const bad = [];
      p.querySelectorAll('*').forEach(el => { const b = el.getBoundingClientRect();
        if (b.width && !el.closest('.bleed,.hd,.ft') && (b.right > r.right - 63.5 || b.bottom > r.top + 912 || b.left < r.left + 63.5)) bad.push(String(el.className && el.className.baseVal !== undefined ? el.className.baseVal : el.className) || el.tagName); });
      return bad.length ? (i + 1) + ': ' + [...new Set(bad)].slice(0, 4).join(' | ') : null; }).filter(Boolean)`);
    if (overflow.length) console.log("overflow:", overflow);

    const pngDir = join(here, "png");
    rmSync(pngDir, { recursive: true, force: true });
    mkdirSync(pngDir, { recursive: true });
    for (let i = 0; i < pages; i += 1) {
      const shot = await cmd("Page.captureScreenshot", { format: "png", captureBeyondViewport: true,
        clip: { x: 0, y: i * 1000, width: 1440, height: 1000, scale: 1 } });
      writeFileSync(join(pngDir, `${String(i + 1).padStart(2, "0")}.png`), Buffer.from(shot.data, "base64"));
    }
    const pdf = await cmd("Page.printToPDF", { printBackground: true, preferCSSPageSize: true,
      displayHeaderFooter: false, marginTop: 0, marginBottom: 0, marginLeft: 0, marginRight: 0, generateTaggedPDF: true });
    const out = join(root, "brand/space-works-brand-guidelines-v2.pdf");
    writeFileSync(out, Buffer.from(pdf.data, "base64"));
    console.log(`PDF ${out} ${(statSync(out).size / 1048576).toFixed(2)} MB, ${pages} pages`);
    await cmd("Browser.close").catch(() => {});
    ws.close();
  } finally {
    const exited = new Promise((r) => (edge.exitCode !== null ? r() : edge.once("exit", r)));
    await Promise.race([exited, sleep(3000)]);
    if (edge.exitCode === null) { edge.kill(); await Promise.race([exited, sleep(3000)]); }
    // Edge's helper processes can hold the profile for a moment after the browser exits.
    for (let i = 0; i < 20; i += 1) {
      try { rmSync(profile, { recursive: true, force: true }); break; } catch { await sleep(500); }
    }
    if (existsSync(profile)) console.warn(`could not remove ${profile}; delete it by hand`);
  }
}

const pages = assemble();
console.log(`assembled ${pages} pages`);
if (!process.argv.includes("--html")) await render(pages);
