import { cssName, json, resolve } from './model.mjs';

export function cssValue(type, value, token = {}) {
  if (type === 'color') return value.alpha === 1 ? value.hex : `rgb(${value.components.map(c => Math.round(c * 255)).join(' ')} / ${value.alpha})`;
  if (type === 'dimension' || type === 'duration') return `${value.value}${value.unit}`;
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`;
  if (type === 'fontFamily') return value.map(s => /^(sans-serif|serif|system-ui|ui-sans-serif|ui-serif)$/.test(s) ? s : JSON.stringify(s)).join(', ');
  if (type === 'shadow') return value.every(v => v.color.alpha === 0) ? 'none' : value.map(v => `${cssValue('dimension', v.offsetX)} ${cssValue('dimension', v.offsetY)} ${cssValue('dimension', v.blur)} ${cssValue('dimension', v.spread)} ${cssValue('color', v.color)}`).join(', ');
  if (type === 'typography') return `${value.fontWeight} ${cssValue('dimension', value.fontSize)}/${value.lineHeight} ${cssValue('fontFamily', value.fontFamily)}`;
  return token.percent ? value * 100 + '%' : String(value);
}
function aliasCss(value) {
  return typeof value === 'string' && /^\{[^{}]+\}$/.test(value) ? `var(${cssName(value.slice(1, -1))})` : null;
}
export function webExports(model) {
  const files = {};
  for (const mode of model.config.modes) {
    const tree = { $description: `Space Works ${model.config.version}; ${mode}; DTCG 2025.10`, $extensions: { 'org.spaceworks': { mode, baseFontPx: model.config.baseFontPx } } };
    for (const [path, token] of Object.entries(model.tokens)) {
      const segments = path.split('.');
      let group = tree;
      for (const segment of segments.slice(0, -1)) group = group[segment] ??= {};
      group[segments.at(-1)] = { $type: token.type, $value: token.values[mode], $description: token.purpose,
        $extensions: { 'org.spaceworks': { use: token.use, avoid: token.avoid, partner: token.partner, scope: token.scope, override: token.override, css: cssName(path), legacy: token.legacy ?? null } } };
    }
    files[`tokens/dtcg/${mode}.tokens.json`] = json(tree);
  }
  const css = ['/* Generated by scripts/tokens/generate.mjs. Do not edit. */', '@import "./tokens.css";', ''];
  for (const mode of model.config.modes) {
    css.push(mode === 'light' ? ':root, [data-sw-tenant] {' : ':root.dark, :root.dark [data-sw-tenant] {');
    for (const [path, token] of Object.entries(model.tokens)) {
      let value = aliasCss(token.values[mode]) ?? cssValue(token.type, resolve(model, path, mode), token);
      if (token.legacy?.css) value = `rgb(var(${token.legacy.css}))`;
      if (token.legacyCss) value = `var(${token.legacyCss})`;
      css.push(`  ${cssName(path)}: ${value};`);
      // Composite typography also exposes independently applicable properties.
      if (token.type === 'typography') for (const [field, raw] of Object.entries(resolve(model, path, mode))) {
        const suffix = field.replace(/[A-Z]/g, c => '-' + c.toLowerCase());
        const type = { fontFamily: 'fontFamily', fontSize: 'dimension', fontWeight: 'fontWeight', letterSpacing: 'dimension', lineHeight: 'number' }[field];
        const source = typeof token.values[mode] === 'string' ? `var(${cssName(token.values[mode].slice(1, -1))}-${suffix})` : aliasCss(token.values[mode][field]);
        css.push(`  ${cssName(path)}-${suffix}: ${source ?? cssValue(type, raw)};`);
      }
    }
    css.push('}', '');
  }
  // Rebind these legacy-variable bridges locally: inherited aliases otherwise resolve at root.
  css.push('.sw-kiosk, .sw-tv {');
  for (const [p, t] of Object.entries(model.tokens)) if (t.legacyCss && p.startsWith('semantic.motion.') && !p.includes('duration-') && !p.includes('easing-')) css.push(`  ${cssName(p)}: var(${t.legacyCss});`);
  css.push('}', '');
  // Accessibility changes semantic behaviour; the primitive scale remains immutable.
  const reduce = Object.entries(model.tokens).filter(([p]) => p.startsWith('semantic.motion.duration-') || /^semantic\.motion\.(enter-y|pop-scale|pop-offset|slide-x)$/.test(p));
  css.push('@media (prefers-reduced-motion: reduce) {', '  :root, :root.dark, [data-sw-tenant], :root.dark [data-sw-tenant] {');
  for (const [p, t] of reduce) css.push(`    ${cssName(p)}: ${t.type === 'duration' ? '0ms' : t.type === 'dimension' ? '0px' : p.endsWith('pop-scale') ? '1' : p.endsWith('slide-x') ? '0%' : '0'};`);
  css.push('  }', '}', '');
  files['tokens/portable.css'] = css.join('\n');
  const preset = { darkMode: 'class', theme: { extend: {} } };
  const extend = preset.theme.extend;
  extend.colors = Object.fromEntries(Object.keys(model.legacy.light).map(k => [k, `rgb(var(--color-${k}) / <alpha-value>)`]));
  for (const [p, t] of Object.entries(model.tokens)) if (p.startsWith('semantic.color.') && !t.legacy) extend.colors['sw-' + p.split('.').at(-1)] = `var(${cssName(p)})`;
  for (const [group, property] of [['spacing', 'spacing'], ['radius', 'borderRadius'], ['border-width', 'borderWidth'], ['layer', 'zIndex'], ['opacity', 'opacity']]) {
    extend[property] = Object.fromEntries(Object.entries(model.tokens).filter(([p]) => p.startsWith(`semantic.${group}.`)).map(([p, t]) => [group === 'spacing' ? String(Number(p.split('.').at(-1)) / 4) : p.split('.').at(-1), `var(${cssName(p)})`]));
  }
  extend.borderRadius.DEFAULT = 'var(--sw-semantic-radius-base)';
  extend.screens = Object.fromEntries(Object.keys(model.config.breakpoint).map(k => [k, model.config.breakpoint[k] + 'px']));
  extend.fontSize = {};
  for (const k of Object.keys(model.config.type)) {
    const v = resolve(model, 'semantic.type.' + k, 'light');
    extend.fontSize[k] = [v.fontSize.value / 16 + 'rem', { lineHeight: String(v.lineHeight), letterSpacing: v.letterSpacing.value / v.fontSize.value + 'em' }];
  }
  extend.fontFamily = Object.fromEntries(['display', 'sans', 'accent'].map(k => [k, resolve(model, 'primitive.font-family.' + k, 'light')]));
  extend.boxShadow = { overlay: 'var(--sw-semantic-elevation-overlay)', none: 'none' };
  extend.transitionDuration = Object.fromEntries(['none', 'fast', 'base', 'slow'].map(k => [k, `var(--sw-semantic-motion-duration-${k})`]));
  extend.transitionTimingFunction = Object.fromEntries(['standard', 'enter', 'exit', 'out-soft'].map(k => [k, `var(--sw-semantic-motion-easing-${k})`]));
  files['tokens/tailwind.preset.cjs'] = '// Generated; import tokens/portable.css once. Tailwind 3 preset / Tailwind 4 @config.\nmodule.exports = ' + json(preset).trimEnd() + ';\n';
  return files;
}
